"""
This module builds the body of the paper LaTeX tables from the dropout
reconstruction results stored in results/drop/*.csv (generated by
src.xai.re_tables).

Run from the root directory:

    python -m src.xai.drop_latex
"""

# Standard libraries
import os

# 3pps
import pandas as pd

# Own modules
from src.utils import DATASETS_NAME, MODEL_NAMES
from src.xai.constants import METHODS

# Static variables
RESULTS_PATH: str = "results/drop"
OUTPUT_PATH: str = "results/drop/latex"


def main() -> None:
    """
    This function builds the LaTeX table body for every drop results
    csv.

    Returns:
        None.
    """

    # Create output dir if it doesn't exist
    os.makedirs(OUTPUT_PATH, exist_ok=True)

    # Iter over dataset, model and method
    for dataset_name in DATASETS_NAME:
        for model_name in MODEL_NAMES:
            for method_name in METHODS:
                file_name: str = f"{dataset_name}_{model_name}_{method_name}"
                csv_path: str = f"{RESULTS_PATH}/{file_name}.csv"

                # Skip missing results
                if not os.path.isfile(csv_path):
                    print(f"Skipping {csv_path}: file not found")
                    continue

                # Csv has two header rows (column name and threshold)
                df: pd.DataFrame = pd.read_csv(csv_path, header=[0, 1], index_col=0)

                with open(
                    f"{OUTPUT_PATH}/{file_name}.tex", "w", encoding="utf-8"
                ) as file:
                    file.write(render_body(df))

    return None


def render_body(df: pd.DataFrame) -> str:
    """
    This function renders the body of the LaTeX table. The first column
    must be the number of clusters and the rest the values, in the
    order they appear in the table.

    Args:
        df: Dataframe read from a drop results csv.

    Returns:
        Body of the LaTeX table.
    """

    # Group rows by number of clusters, keeping the csv order
    clusters: pd.Series = df.iloc[:, 0].astype(int)
    groups: list[tuple[int, pd.DataFrame]] = [
        (int(num_clusters), df[clusters == num_clusters])
        for num_clusters in clusters.unique()
    ]

    lines: list[str] = []
    for i, (num_clusters, group) in enumerate(groups):
        num_rows: int = len(group)
        is_last: bool = i == len(groups) - 1
        row_word: str = "row" if num_rows == 1 else "rows"

        lines.append(f"        % cluster {num_clusters} ({num_rows} {row_word})")
        lines.append(f"        \\multirow{{{num_rows}}}{{*}}{{{num_clusters}}}")
        for values in group.iloc[:, 1:].to_numpy():
            cells: str = " & ".join(format_value(float(value)) for value in values)
            lines.append(f"            & {cells} \\\\")
        lines.append(r"        \bottomrule" if is_last else r"        \midrule")
        if not is_last:
            lines.append("")

    return "\n".join(lines) + "\n"


def format_value(value: float) -> str:
    """
    This function formats a value with two decimals, avoiding '-0.00'.

    Args:
        value: Value to format.

    Returns:
        Formatted value.
    """

    text: str = f"{value:.2f}"

    return "0.00" if text == "-0.00" else text


if __name__ == "__main__":
    main()
